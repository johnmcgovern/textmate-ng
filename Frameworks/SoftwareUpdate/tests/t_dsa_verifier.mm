// ==================================================================
// = The arithmetic underneath                                      =
// ==================================================================
//
// Division is where a big-integer bug hides: Knuth's algorithm D estimates each
// quotient digit and, about twice in every 2^32 divisions, estimates one too
// high and has to add the divisor back. No DSA signature reaches that branch by
// accident — 400,000 random divisions did not — so the first three vectors were
// searched for on purpose, by constructing dividends whose remainder sits just
// under the divisor. Deleting the add-back correction fails this test and
// nothing else in the file.
//
// Every expected value here is Python's, from its arbitrary-precision integers.

struct division_vector_t { char const* name; std::vector<uint8_t> u, v, q, r; };

static NSData* bytes (std::vector<uint8_t> const& v)
{
	return [NSData dataWithBytes:v.data() length:v.size()];
}

static std::string hexed (NSData* data)
{
	std::string res;
	uint8_t const* raw = (uint8_t const*)data.bytes;
	for(NSUInteger i = 0; i < data.length; ++i)
		res += text::format("%02X", raw[i]);
	return res;
}

