// The DSA verifier that replaced SecTransform on 2026-09-17 (DSAVerifier.swift).
// It verifies MacroMates' bundle index, so a verifier that said yes too often
// would let a tampered index install tampered bundles, and one that said no too
// often would stop bundle updates entirely. Both directions are pinned.
//
// The fixtures are openssl's, generated with `openssl dsaparam` / `gendsa` /
// `dgst -sha1 -sign`, in the two key shapes the bundle index uses: 1024-bit with
// a 160-bit q (which is what both of MacroMates' keys are) and 2048-bit. The
// last test uses the real key and a real signature off the live server.
//
// Six mutations were tried against this file and each is caught by exactly one
// test: the r/s range guard, the Fermat inverse's exponent, the algorithm OID
// check, Knuth's add-back correction, the multiply's trailing carry, and a
// dropped exponent bit. The first three survived the tests as first written,
// which is how the forgery, Diffie-Hellman and division cases below came to
// exist.

void setup ()
{
	NSApplicationLoad();
}

