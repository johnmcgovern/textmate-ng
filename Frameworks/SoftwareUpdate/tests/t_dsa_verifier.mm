void test_dsa_parses_a_public_key_into_its_parameters ()
{
	NSArray<NSNumber*>* widths = [OakDSAVerifier publicKeyBitWidthsFromPEM:kPublicKey1024];
	OAK_ASSERT_EQ((size_t)widths.count, (size_t)4);
	OAK_ASSERT_EQ([widths[0] intValue], 1024); // p
	OAK_ASSERT_EQ([widths[1] intValue], 160);  // q — the size both real keys use
	OAK_ASSERT_EQ((bool)([widths[3] intValue] > 0), true); // y

	OAK_ASSERT_EQ([[OakDSAVerifier publicKeyBitWidthsFromPEM:kPublicKey2048][0] intValue], 2048);
	OAK_ASSERT((bool)([OakDSAVerifier publicKeyBitWidthsFromPEM:@"nonsense"] == nil));
}

void test_dsa_refuses_a_key_that_is_not_dsa ()
{
	// An EC public key, in the same PEM shape. Its parameters are a single OID
	// rather than a SEQUENCE, so the structure alone turns this away.
	NSString* ecKey = @"-----BEGIN PUBLIC KEY-----\n"
	                   "MFkwEwYHKoZIzj0CAQYIKoZIzj0DAQcDQgAEqbXPjQ7ZKJmFY1kGAEwnp5Ic0zHl\n"
