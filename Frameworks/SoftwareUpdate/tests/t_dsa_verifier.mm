void test_dsa_rejects_an_altered_payload ()
{
	// One byte different, everything else the same. This is the case the whole
	// file exists for: a bundle index edited in transit.
	NSData* tampered = [@"the quick brown fox jumps over the lazy dov\n" dataUsingEncoding:NSUTF8StringEncoding];
	OAK_ASSERT_EQ((bool)[OakDSAVerifier verifyData:tampered derSignature:decode(kSignature1024) pemPublicKey:kPublicKey1024], false);
}

void test_dsa_rejects_a_signature_from_another_key ()
{
	// Same parameters, same payload, different private key.
	OAK_ASSERT_EQ((bool)[OakDSAVerifier verifyData:payload() derSignature:decode(kOtherSignature) pemPublicKey:kPublicKey1024], false);
	// And the mirror, so the test cannot pass by rejecting everything.
	OAK_ASSERT_EQ((bool)[OakDSAVerifier verifyData:payload() derSignature:decode(kOtherSignature) pemPublicKey:kOtherPublicKey], true);
}

void test_dsa_rejects_a_signature_with_a_flipped_bit ()
{
	NSMutableData* broken = [decode(kSignature1024) mutableCopy];
	uint8_t* bytes = (uint8_t*)broken.mutableBytes;
	bytes[broken.length - 1] ^= 0x01;
	OAK_ASSERT_EQ((bool)[OakDSAVerifier verifyData:payload() derSignature:broken pemPublicKey:kPublicKey1024], false);
}

void test_dsa_rejects_zero_and_out_of_range_values ()
{
	// r = 0, s = 0. Without the range check these drive the arithmetic to v = 0,
	// which compares equal to r and accepts anything — the classic DSA forgery.
	uint8_t zeros[] = { 0x30, 0x06, 0x02, 0x01, 0x00, 0x02, 0x01, 0x00 };
	OAK_ASSERT_EQ((bool)[OakDSAVerifier verifyData:payload() derSignature:[NSData dataWithBytes:zeros length:sizeof(zeros)] pemPublicKey:kPublicKey1024], false);

	// r = 1, s = 1: in range as integers, but not a signature.
	uint8_t ones[] = { 0x30, 0x06, 0x02, 0x01, 0x01, 0x02, 0x01, 0x01 };
	OAK_ASSERT_EQ((bool)[OakDSAVerifier verifyData:payload() derSignature:[NSData dataWithBytes:ones length:sizeof(ones)] pemPublicKey:kPublicKey1024], false);
}

void test_dsa_rejects_malformed_input_without_crashing ()
{
	// Every one of these reaches the DER reader, which must refuse rather than
	// read past the end. A crash here would be a denial of service triggered by
	// a response header.
	NSData* good = decode(kSignature1024);

	OAK_ASSERT_EQ((bool)[OakDSAVerifier verifyData:payload() derSignature:[NSData data] pemPublicKey:kPublicKey1024], false);
	OAK_ASSERT_EQ((bool)[OakDSAVerifier verifyData:payload() derSignature:[good subdataWithRange:NSMakeRange(0, 4)] pemPublicKey:kPublicKey1024], false);

	uint8_t truncatedLength[] = { 0x30, 0x7F, 0x02 };           // says 127 bytes follow, three do
	OAK_ASSERT_EQ((bool)[OakDSAVerifier verifyData:payload() derSignature:[NSData dataWithBytes:truncatedLength length:sizeof(truncatedLength)] pemPublicKey:kPublicKey1024], false);

	uint8_t absurdLength[] = { 0x30, 0x84, 0x7F, 0xFF, 0xFF, 0xFF, 0x02, 0x01, 0x01 };
	OAK_ASSERT_EQ((bool)[OakDSAVerifier verifyData:payload() derSignature:[NSData dataWithBytes:absurdLength length:sizeof(absurdLength)] pemPublicKey:kPublicKey1024], false);

	uint8_t negative[] = { 0x30, 0x06, 0x02, 0x01, 0xFF, 0x02, 0x01, 0x01 }; // high bit set: negative
	OAK_ASSERT_EQ((bool)[OakDSAVerifier verifyData:payload() derSignature:[NSData dataWithBytes:negative length:sizeof(negative)] pemPublicKey:kPublicKey1024], false);

	OAK_ASSERT_EQ((bool)[OakDSAVerifier verifyData:payload() derSignature:good pemPublicKey:@"not a pem at all"], false);
	OAK_ASSERT_EQ((bool)[OakDSAVerifier verifyData:payload() derSignature:good pemPublicKey:@"-----BEGIN PUBLIC KEY-----\nZm9v\n-----END PUBLIC KEY-----\n"], false);
}

void test_dsa_refuses_the_r_is_one_s_is_zero_forgery ()
{
	// **A universal forgery if the range guard is missing.** With s = 0 the
	// Fermat inverse gives w = 0, so u1 = u2 = 0 and v = (g^0 * y^0 mod p) mod q
	// = 1 — which equals r. That signature then verifies against *any* message
	// under *any* key. FIPS 186-4 requires 0 < r < q and 0 < s < q for exactly
	// this reason, and deleting that line from the verifier fails this test
	// alone: (0,0) and (1,1), which this file also checks, are refused by the
	// arithmetic whether the guard is there or not, so they prove nothing about
	// it. Found by mutating the guard away and noticing nothing failed.
	uint8_t forged[] = { 0x30, 0x06, 0x02, 0x01, 0x01, 0x02, 0x01, 0x00 }; // r = 1, s = 0
	NSData* signature = [NSData dataWithBytes:forged length:sizeof(forged)];

	OAK_ASSERT_EQ((bool)[OakDSAVerifier verifyData:payload() derSignature:signature pemPublicKey:kPublicKey1024], false);
	OAK_ASSERT_EQ((bool)[OakDSAVerifier verifyData:payload() derSignature:signature pemPublicKey:kPublicKey2048], false);
	// And against a message it was never near.
	OAK_ASSERT_EQ((bool)[OakDSAVerifier verifyData:[@"anything at all" dataUsingEncoding:NSUTF8StringEncoding] derSignature:signature pemPublicKey:kPublicKey1024], false);
}

